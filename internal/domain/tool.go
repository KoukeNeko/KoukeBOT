package domain

import "context"

// Tool represents a capability that the LLM can invoke during conversation.
// Inspired by OpenClaw's tool system for extending LLM capabilities.
type Tool interface {
	// Name returns the unique identifier for this tool (e.g., "web_search")
	Name() string

	// Description returns a human-readable description of what this tool does.
	// This is shown to the LLM to help it decide when to use the tool.
	Description() string

	// InputSchema returns the JSON Schema for the tool's input parameters.
	// This defines what parameters the LLM can pass to the tool.
	InputSchema() map[string]interface{}

	// Execute runs the tool with the given input and returns the result.
	// The input map contains the parameters specified in InputSchema.
	Execute(ctx context.Context, input map[string]interface{}) (ToolResult, error)
}

// ToolCall represents an LLM's request to use a tool.
// This is generated by the LLM when it decides a tool is needed.
type ToolCall struct {
	ID    string                 `json:"id"`    // Unique identifier for this tool call
	Name  string                 `json:"name"`  // Name of the tool to invoke
	Input map[string]interface{} `json:"input"` // Parameters for the tool
}

// ToolResult represents the outcome of a tool execution.
// This is returned to the LLM to continue the conversation.
type ToolResult struct {
	ToolCallID string `json:"tool_call_id"` // Links back to the ToolCall.ID
	Content    string `json:"content"`      // Result data (usually JSON)
	IsError    bool   `json:"is_error"`     // Whether execution failed
}
